// ---------------------------------------------------------------------------
// Кладёт настоящую страницу «не найдено» в /404.html.
//
// ЗАЧЕМ. Хостинг — App Platform в Timeweb Cloud, своей конфигурации
// веб-сервера там нет. Поведение на несуществующем адресе задаётся одним
// переключателем «SPA Fallback» в настройках приложения:
//
//   включён  — сервер отдаёт /index.html с кодом 200. Именно так сайт
//              работает сейчас: любой битый адрес возвращает копию главной,
//              поисковик видит бесконечное число страниц с одинаковым
//              содержимым, а человек не понимает, что ошибся адресом;
//   выключен — сервер отдаёт /404.html с кодом 404.
//
// Выключить переключатель можно и сейчас, но толку будет мало: nuxt generate
// кладёт в /404.html пустую оболочку приложения на ~1,8 КБ, которая рисуется
// только скриптом. Поисковик получил бы правильный код и пустую страницу.
//
// Настоящая страница с заголовком «Этот брус куда-то делся» и пометкой
// noindex лежит в /404/index.html — она собрана заранее и содержит весь текст.
// Этот скрипт копирует её в /404.html, чтобы после выключения SPA Fallback
// хостинг отдавал готовую страницу, а не оболочку.
//
// Страница по адресу /404/ остаётся на месте: ссылки на неё не ломаются.
// ---------------------------------------------------------------------------
import { copyFile, stat, readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { existsSync } from 'node:fs'

// Путь сборки: на машине разработчика есть ссылка dist, на сборке из
// GitHub её нет — см. тот же разбор в scripts/sitemap.mjs.
const DIST = existsSync('.output/public') ? '.output/public' : 'dist'
const SOURCE = join(DIST, '404', 'index.html')
const TARGET = join(DIST, '404.html')

try {
  const before = await stat(TARGET).then(s => s.size).catch(() => 0)
  const html = await readFile(SOURCE, 'utf8')

  // Если страница собралась неправильно, лучше упасть на сборке, чем отдать
  // посетителю пустоту. Проверяем, что в файле есть и текст, и запрет на
  // индексацию.
  if (!/noindex/i.test(html)) {
    throw new Error('в 404/index.html нет пометки noindex — проверьте app/pages/404.vue')
  }
  if (html.length < 4000) {
    throw new Error(`404/index.html подозрительно мал (${html.length} Б) — похоже, это оболочка, а не страница`)
  }

  await copyFile(SOURCE, TARGET)
  const after = await stat(TARGET).then(s => s.size)
  console.log(`404.html: заменён настоящей страницей, ${before} → ${after} Б`)
  console.log('   не забудьте выключить «SPA Fallback» в настройках приложения —')
  console.log('   без этого хостинг продолжит отдавать копию главной с кодом 200')
}
catch (e) {
  console.error('404.html: не удалось подготовить —', e.message)
  process.exitCode = 1
}
